//! Messages of the real frontend. Each one either changes view state or sends a
//! command to the core worker — never both behind the UI's back.

use crate::real::state::Screen;

/// One user, timer or controller-driven event.
#[derive(Debug, Clone)]
pub enum Message {
    /// The poll timer fired: refresh the snapshot, cover and lyrics.
    Poll,
    ServiceAction(super::services::Action),
    ServiceFinished(
        u64,
        super::services::Action,
        Result<super::services::Reply, String>,
    ),
    ServiceField(usize, String),
    ServiceSecret(usize, muzon_services::Secret),
    ServicePathStyle(bool),
    ServiceCancel,
    ServiceOpenAuth,
    ServiceCopyAuth,
    ServiceBrowser(Result<(), String>),
    AppearanceChanged(super::appearance::Change),
    AppearanceAccentInput(String),
    AppearanceAccentApply,
    AppearanceFileInput(String),
    AppearanceImport,
    AppearanceRyoku,
    AppearanceRefresh,
    AppearanceThemeLoaded(u64, Result<super::appearance::ThemeSource, String>),
    AppearanceSystem(Option<bool>),
    AppearanceSave,
    AppearanceSaved(u64, Result<(), String>),
    OpenEditor(i32),
    EditorLoaded(u64, Result<muzon_core::editing::EditorSource, String>),
    EditorField(usize, String),
    EditorText(iced::widget::text_editor::Action),
    EditorTab(super::editor::Tab),
    EditorStorage(bool),
    EditorSave,
    EditorTimestamp,
    EditorFetch,
    EditorFetched(
        u64,
        u64,
        Result<Option<muzon_core::data::lrclib::Suggestion>, String>,
    ),
    EditorFetchCancel,
    EditorUseSuggestion,
    EditorDismissSuggestion,
    EditorTapStart,
    EditorTapStamp,
    EditorTapUndo,
    EditorTapFinish,
    EditorTapCancel,
    EditorSaved(u64, super::editor::Tab, Result<(), String>),
    EditorClose,
    EditorDiscard,
    EditorKeep,
    AlbumCovers(u64, super::album_grid::Loaded),
    AlbumsBack,
    AlbumSelected(super::groups::GroupKey),
    GroupSelected(usize),
    SmartSelected(super::smart::Smart),
    QueueMove(usize, usize),
    GroupsScrolled(f32),
    SetSleep(muzon_core::sleep_timer::SleepChoice),
    Shortcut(super::shortcuts::Shortcut),
    PaletteQuery(String),
    PaletteClose,
    PaletteExecute,
    PaletteRun(usize),
    QueueDragStart(usize),
    QueueDragHover(usize),
    QueueDragRelease,
    WindowFocusLost,
    KeyReleased(iced::keyboard::Key),
    KeyPressed(iced::keyboard::Key, iced::keyboard::Modifiers, bool),
    HotkeyCapture(usize),
    HotkeysReset,
    HotkeysSave,
    HotkeysSaved(u64, Result<(), String>),
    WindowOpened(iced::window::Id),
    WindowResized(iced::window::Id, iced::Size),
    WindowObserved(u64, iced::Size, bool),
    WindowSaved(u64, Result<(), String>),
    AudioChanged(muzon_core::domain::playback_settings::PlaybackEdit),
    AudioPreset(usize),
    AudioSave,
    AudioSaved(Result<(), String>),
    TrackTempoChanged {
        id: i32,
        rate: f64,
    },
    ResetTrackTempo(i32),
    ResetAudioEffects,
    /// Search box text changed. Filters the view only; the playing queue is
    /// never touched.
    SearchChanged(String),
    /// A row of the filtered library was clicked; the payload is a row index
    /// in the *filtered* list.
    TrackRowClicked(usize),
    EnqueueRow(usize),
    ToggleFavorite(i32),
    FavoriteFinished {
        id: i32,
        result: Result<(), String>,
    },
    NewPlaylistName(String),
    RenamePlaylistName(String),
    CreatePlaylist,
    RenamePlaylist,
    PlaylistSelected(i32),
    EditPlaylist(muzon_core::controller::PlaylistEdit),
    PlaylistFinished(Result<Option<i32>, String>),
    OpenPlaylistPicker(i32),
    AskDeletePlaylist(i32),
    CloseCollectionOverlay,
    PlayCollection,
    EnqueueCollection,
    PlaylistListScrolled(f32),
    PlaylistPickerScrolled(f32),
    /// A row of the queue view was clicked; payload is a position in the
    /// display order (`Snapshot::display`).
    QueueRowClicked(usize),
    /// Remove the queue element behind a display position.
    QueueRemove(usize),
    /// Play/pause, as the controller sees it.
    TogglePlay,
    Stop,
    Next,
    Previous,
    /// Seek slider moved: a preview, nothing is sent yet.
    SeekChanged(f64),
    /// Seek slider released: commit the previewed position.
    SeekCommit,
    /// Volume slider moved.
    VolumeChanged(f64),
    ToggleShuffle,
    CycleRepeat,
    /// The path field in the library screen changed.
    FolderInputChanged(String),
    PickFolder,
    FolderPicked(Option<std::path::PathBuf>),
    TrackCovers(u64, super::track_covers::Loaded),
    /// Add the typed folder as a library root and rescan.
    AddFolder,
    /// Rescan every known root.
    Rescan,
    /// Switch the main screen.
    ScreenSelected(Screen),
    LibraryScrolled(f32),
    QueueScrolled(f32),
    /// Explicit shutdown: stop the engine, flush the session, leave.
    Quit,
    DiscardAudioAndQuit,
    WindowCloseRequested(Option<iced::window::Id>),
    QuitRequested(Option<iced::window::Id>),
    WindowCloseReady(Option<iced::window::Id>, Option<(iced::Size, bool)>),
    ShutdownComplete(Option<iced::window::Id>, Result<(), String>),
    ShutdownAudioSaved(Option<iced::window::Id>, Result<(), String>),
}
